# Generates src/tz_db.h: the IANA to POSIX timezone table.

"""IANA zone name -> POSIX TZ string, for tzPosix() (src/tz.cpp).

The badge gets the wearer's zone from the app as an IANA name ("America/New_York"), but newlib's
setenv("TZ") only understands POSIX rules ("EST5EDT,M3.2.0,M11.1.0"). Every TZif v2+ file ends
with exactly that rule on its last line, so the table comes straight from a zoneinfo directory.
Run from the project folder (any Mac or Linux box has one):

    python3 tools/make_tz.py [/usr/share/zoneinfo]
"""
import os
import sys

root = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/zoneinfo"
out_path = "src/tz_db.h"

zones = {}
for dirpath, dirnames, filenames in os.walk(root):
    rel_dir = os.path.relpath(dirpath, root)
    if rel_dir.split(os.sep)[0] in ("posix", "right"):   # duplicate trees on some systems
        dirnames[:] = []
        continue
    for f in filenames:
        name = os.path.normpath(os.path.join(rel_dir, f)).replace(os.sep, "/")
        if name in ("posixrules", "Factory", "localtime"):
            continue
        with open(os.path.join(dirpath, f), "rb") as fh:
            data = fh.read()
        if not data.startswith(b"TZif") or data[4:5] < b"2":
            continue
        footer = data.rstrip(b"\n").rsplit(b"\n", 1)[-1].decode("ascii")
        if footer:
            zones[name] = footer

version = ""
try:
    with open(os.path.join(root, "+VERSION")) as fh:
        version = fh.read().strip()
except OSError:
    pass

rules = sorted(set(zones.values()))
index = {r: i for i, r in enumerate(rules)}
names = sorted(zones)   # byte order = strcmp order, for the binary search

lines = [
    "#pragma once",
    "// Generated by tools/make_tz.py from %s%s — do not edit."
    % (root, " (tzdata %s)" % version if version else ""),
    "// IANA zone name -> POSIX TZ rule. TZ_ZONES is sorted by name (strcmp) for a binary search.",
    "#include <stdint.h>",
    "",
    "static const char* const TZ_RULES[] = {",
]
lines += ['  "%s",' % r for r in rules]
lines += ["};", "", "struct TzZone { const char* name; uint16_t rule; };", "",
          "static const TzZone TZ_ZONES[] = {"]
lines += ['  {"%s", %d},' % (n, index[zones[n]]) for n in names]
lines += ["};", ""]

with open(out_path, "w") as fh:
    fh.write("\n".join(lines))
print("%s: %d zones, %d distinct rules" % (out_path, len(names), len(rules)))
