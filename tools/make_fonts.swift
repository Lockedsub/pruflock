// Generates src/fonts.h: anti-aliased TFT_eSPI smooth fonts (VLW) with German umlauts.

// The built-in TFT_eSPI fonts are ASCII-only. Liberation Sans has Arial's metrics under a free
// license (tools/fonts/). Needs macOS (CoreText). Run from the project folder:
//   swift tools/make_fonts.swift
//
// VLW layout (see TFT_eSPI Extensions/Smooth_font.cpp, all int32 big-endian):
//   header:  glyphCount, version, size, 0, ascent, descent
//   glyph:   unicode, height, width, xAdvance, dY (top above baseline), dX, 0     (×glyphCount)
//   bitmaps: width×height alpha bytes per glyph, in table order

import CoreText
import CoreGraphics
import Foundation

let chars: [UInt32] = Array(0x21...0x7E) + "ÄÖÜäöüß°·–…".unicodeScalars.map { $0.value }

struct FontSpec { let name: String; let file: String; let size: CGFloat }
let specs = [
  FontSpec(name: "FONT_SMALL", file: "tools/fonts/LiberationSans-Bold.ttf", size: 16),
  FontSpec(name: "FONT_LARGE", file: "tools/fonts/LiberationSans-Bold.ttf", size: 24),
]

func be32(_ v: Int32, _ out: inout [UInt8]) {
  let u = UInt32(bitPattern: v)
  out += [UInt8(u >> 24 & 0xFF), UInt8(u >> 16 & 0xFF), UInt8(u >> 8 & 0xFF), UInt8(u & 0xFF)]
}

func makeVlw(_ spec: FontSpec) -> [UInt8] {
  let url = URL(fileURLWithPath: spec.file) as CFURL
  guard let descs = CTFontManagerCreateFontDescriptorsFromURL(url) as? [CTFontDescriptor], let d = descs.first else {
    fatalError("cannot load \(spec.file)")
  }
  let font = CTFontCreateWithFontDescriptor(d, spec.size, nil)

  var table: [[Int32]] = []
  var bitmaps: [UInt8] = []
  var ascent: Int32 = 0, descent: Int32 = 0

  for cp in chars {
    var utf16 = Array(String(UnicodeScalar(cp)!).utf16)
    var glyphs = [CGGlyph](repeating: 0, count: utf16.count)
    guard CTFontGetGlyphsForCharacters(font, &utf16, &glyphs, utf16.count), glyphs[0] != 0 else {
      print("  skip U+\(String(cp, radix: 16)) (not in font)"); continue
    }
    var g = glyphs[0]
    let bbox = CTFontGetBoundingRectsForGlyphs(font, .horizontal, &g, nil, 1)
    var adv = CGSize.zero
    CTFontGetAdvancesForGlyphs(font, .horizontal, &g, &adv, 1)

    let minX = floor(bbox.minX), maxX = ceil(bbox.maxX)
    let minY = floor(bbox.minY), maxY = ceil(bbox.maxY)
    let w = max(1, Int(maxX - minX)), h = max(1, Int(maxY - minY))

    var buf = [UInt8](repeating: 0, count: w * h)
    let ctx = CGContext(data: &buf, width: w, height: h, bitsPerComponent: 8, bytesPerRow: w,
                        space: CGColorSpaceCreateDeviceGray(), bitmapInfo: CGImageAlphaInfo.none.rawValue)!
    ctx.setShouldAntialias(true)
    ctx.setAllowsFontSmoothing(false)
    ctx.setFillColor(gray: 1, alpha: 1)
    var pos = CGPoint(x: -minX, y: -minY)
    CTFontDrawGlyphs(font, &g, &pos, 1, ctx)
    ctx.flush()

    let dY = Int32(maxY), dX = Int32(minX)
    table.append([Int32(cp), Int32(h), Int32(w), Int32(adv.width.rounded()), dY, dX, 0])
    bitmaps += buf   // CGBitmapContext memory is top row first, as VLW expects
    ascent = max(ascent, dY)
    descent = max(descent, Int32(h) - dY)
  }

  var out: [UInt8] = []
  for v in [Int32(table.count), 11, Int32(spec.size), 0, ascent, descent] { be32(v, &out) }
  for row in table { for v in row { be32(v, &out) } }
  out += bitmaps
  print("\(spec.name): \(table.count) glyphs, \(out.count) bytes, ascent \(ascent), descent \(descent)")
  return out
}

var header = """
#pragma once
// Generated by tools/make_fonts.swift — do not edit. Liberation Sans Bold (SIL OFL 1.1, see
// tools/fonts/LiberationSans-LICENSE.txt), rasterized to TFT_eSPI smooth fonts (VLW) with German
// umlauts. Load with spr.loadFont(FONT_SMALL).
#include <Arduino.h>


"""
for spec in specs {
  let bytes = makeVlw(spec)
  header += "static const uint8_t \(spec.name)[] PROGMEM = {\n"
  for chunk in stride(from: 0, to: bytes.count, by: 20) {
    let line = bytes[chunk..<min(chunk + 20, bytes.count)].map { String(format: "0x%02X", $0) }.joined(separator: ",")
    header += "  \(line),\n"
  }
  header += "};\n\n"
}
let outPath = CommandLine.arguments.count > 1 ? CommandLine.arguments[1] : "src/fonts.h"
try! header.write(toFile: outPath, atomically: true, encoding: .utf8)
print("wrote \(outPath)")
